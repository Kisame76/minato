#!/usr/bin/env python3
"""Writes the Java class of an event log tags file, as build/make's java-event-log-tags.py does (ADR-0039 step
c2c3): a constant per tag and a write method that hands the tag's fields to android.util.EventLog. build/make's
generator is not among the fetched sources; tools/build-framework.sh runs this one for each .logtags file that
framework/sources.txt names, into build/framework/gen/logtags.

The format (system/logging/logcat/event.logtags): "option java_package <package>", then one tag per line,
"<number> <name> (<field>|<type>[|<unit>]),...", with # comments. Types: 1 int, 2 long, 3 string, 4 list, 5 float.

Usage: tools/event-log-tags.py <file.logtags> --out <folder>
"""
import argparse
import os
import re
import sys

JAVA_TYPES = {"1": "int", "2": "long", "3": "String", "4": "Object[]", "5": "float"}
KEYWORDS = {"abstract", "assert", "boolean", "break", "byte", "case", "catch", "char", "class", "const", "continue",
            "default", "do", "double", "else", "enum", "extends", "final", "finally", "float", "for", "goto", "if",
            "implements", "import", "instanceof", "int", "interface", "long", "native", "new", "package", "private",
            "protected", "public", "return", "short", "static", "strictfp", "super", "switch", "synchronized", "this",
            "throw", "throws", "transient", "try", "void", "volatile", "while"}


def java_name(name):
    """A field's name as a parameter: "Component Name" gives componentName, as build/make's javaName."""
    out = name[0].lower() + re.sub(r"[^A-Za-z0-9]", "", name.title())[1:]
    return out + "_" if out in KEYWORDS else out


def camel(tag_name):
    """A tag's name in a method name: wm_on_paused_called gives WmOnPausedCalled."""
    return "".join(part[:1].upper() + part[1:] for part in tag_name.split("_"))


def parse(path):
    """The file's Java package and its tags, each (number, name, [(field, type)], line); exits on a malformed one."""
    package = None
    tags = []
    with open(path, encoding="utf-8") as handle:
        for number, raw in enumerate(handle, 1):
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            option = re.match(r"^option\s+java_package\s+(\S+)$", line)
            if option:
                package = option.group(1)
                continue
            tag = re.match(r"^(\d+)\s+(\w+)\s*(.*)$", line)
            if not tag:
                sys.exit("%s:%d: not a tag: %s" % (path, number, line))
            fields = []
            for field in re.findall(r"\(([^)]*)\)", tag.group(3)):
                parts = field.split("|")
                if len(parts) < 2 or parts[1] not in JAVA_TYPES:
                    sys.exit("%s:%d: bad field (%s)" % (path, number, field))
                fields.append((parts[0], JAVA_TYPES[parts[1]]))
            tags.append((int(tag.group(1)), tag.group(2), fields, line))
    if package is None:
        sys.exit("%s: no option java_package" % path)
    return package, tags


def write(path, out):
    package, tags = parse(path)
    name = os.path.splitext(os.path.basename(path))[0]
    lines = ["/* Generated by tools/event-log-tags.py from %s. Do not edit. */" % os.path.basename(path),
             "package %s;" % package, "", "/**", " * @hide", " */", "public class %s {" % name,
             "    private %s() {" % name, "    }"]
    for number, tag_name, _, line in tags:
        lines += ["", "    /** %s */" % line, "    public static final int %s = %d;" % (tag_name.upper(), number)]
    for _, tag_name, fields, _ in tags:
        if not fields:
            continue
        params = ", ".join("%s %s" % (java_type, java_name(field)) for field, java_type in fields)
        values = ", ".join(java_name(field) for field, _ in fields)
        lines += ["", "    public static void write%s(%s) {" % (camel(tag_name), params),
                  "        android.util.EventLog.writeEvent(%s, %s);" % (tag_name.upper(), values), "    }"]
    lines.append("}")
    folder = os.path.join(out, *package.split("."))
    os.makedirs(folder, exist_ok=True)
    with open(os.path.join(folder, name + ".java"), "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("logtags")
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    write(args.logtags, args.out)


if __name__ == "__main__":
    main()
