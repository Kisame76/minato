#!/usr/bin/env python3
"""The managers' generator (ADR-0045 decision 3): writes our own classes under AOSP's names from the API's
signature files (metalava's format 2.0, core/api/current.txt and the modules' framework/api/current.txt), with the
whole public API, so that a method no one has written logs once instead of failing with NoSuchMethodError.

- Every method's body logs once through com.android.minato.services.Unwritten and returns its type's default:
  0, false, '\\0' or null. Abstract and interface methods keep no body; equals, hashCode and toString stay
  Object's. Constants keep their values; a final field without one gets its type's default in an initializer.
- Nested types (Outer.Inner in the file) go into their outer class. A class without a ctor in the API gets a
  package-private one, so that Java adds no public ctor Android lacks.
- A hand file, <hand>/<package path>/<Class>.java, holds the written part: imports, then one class body. Its
  members replace the generated ones with the same name and erased parameter types (fields and nested types by
  name). A member the API lacks is added when it is private or its javadoc says @hide, as AOSP marks its hidden
  members; any other is an error, so that a typo does not leave the API's method unwritten.

Usage: managergen.py --api <current.txt>... --class <qualified name>... [--hand <folder>] --out <folder>
"""
import argparse
import os
import re
import sys

FORMAT = "// Signature format: 2.0"
MODIFIERS = {"public", "protected", "private", "static", "final", "abstract", "default", "synchronized", "native",
             "transient", "volatile", "strictfp", "sealed", "non-sealed"}
KINDS = {"class", "interface", "enum", "@interface"}
KEPT_ANNOTATIONS = {"@Deprecated"}
OBJECT_METHODS = {"equals(Object)", "hashCode()", "toString()"}
HEADER = "// Generated by tools/managergen (ADR-0045 decision 3) from the API's signature file and the hand file.\n"


class GeneratorError(Exception):
    pass


class TypeDecl:
    def __init__(self, package, name, kind, modifiers, annotations, type_parameters, extends, implements):
        self.package = package
        self.name = name.rsplit(".", 1)[-1]
        self.dotted = name  # Outer.Inner within the package
        self.kind = kind
        self.modifiers = modifiers
        self.annotations = annotations
        self.type_parameters = type_parameters
        self.extends = extends
        self.implements = implements
        self.ctors, self.methods, self.fields, self.constants, self.nested = [], [], [], [], []
        # From a library's API file (libcore's): known for references and superclasses, never written.
        self.library = False

    @property
    def qualified(self):
        return f"{self.package}.{self.dotted}"


class Method:
    def __init__(self, modifiers, annotations, type_parameters, returns, name, parameters, throws, default):
        self.modifiers = modifiers
        self.annotations = annotations
        self.type_parameters = type_parameters
        self.returns = returns
        self.name = name
        self.parameters = parameters
        self.throws = throws
        self.default = default

    @property
    def key(self):
        return f"{self.name}({','.join(erase(p) for p in self.parameters)})"


class Field:
    def __init__(self, modifiers, annotations, type, name, value):
        self.modifiers = modifiers
        self.annotations = annotations
        self.type = type
        self.name = name
        self.value = value


class Api:
    def __init__(self):
        self.types = {}


# Text helpers.

def skip_quoted(text, i):
    """The index after the string or char literal that starts at text[i]."""
    quote = text[i]
    i += 1
    while i < len(text) and text[i] != quote:
        i += 2 if text[i] == "\\" else 1
    return i + 1


def strip_annotations(text):
    """The text without its annotations, and the kept ones (@Deprecated)."""
    out, kept, i = [], [], 0
    while i < len(text):
        c = text[i]
        if c in "\"'":
            end = skip_quoted(text, i)
            out.append(text[i:end])
            i = end
        elif c == "@" and not text.startswith("@interface", i):
            match = re.compile(r"@[\w.]+").match(text, i)
            i = match.end()
            if match.group() in KEPT_ANNOTATIONS:
                kept.append(match.group())
            if i < len(text) and text[i] == "(":
                depth = 0
                while i < len(text):
                    if text[i] in "\"'":
                        i = skip_quoted(text, i)
                        continue
                    depth += {"(": 1, ")": -1}.get(text[i], 0)
                    i += 1
                    if depth == 0:
                        break
        else:
            out.append(c)
            i += 1
    return re.sub(r"\s+", " ", "".join(out)).strip(), kept


def split_top(text, separator):
    """Splits at `separator` outside <>, () and []."""
    parts, depth, current = [], 0, []
    for c in text:
        if c in "<([":
            depth += 1
        elif c in ">)]":
            depth -= 1
        if depth == 0 and (c == separator or (separator == " " and c.isspace())):
            parts.append("".join(current))
            current = []
        else:
            current.append(c)
    parts.append("".join(current))
    return [p.strip() for p in parts if p.strip()]


def erase(java_type):
    """A parameter's type as both files can name it: without generics and package, varargs as an array."""
    without = re.sub(r"<[^<>]*>", "", java_type)
    while "<" in without:
        without = re.sub(r"<[^<>]*>", "", without)
    without = without.replace("...", "[]").replace(" ", "")
    base = without.rstrip("[]")
    return base.rsplit(".", 1)[-1] + without[len(base):]


def log_type(java_type):
    """A parameter's type as the log line names it: the API's text without generics."""
    without = java_type
    while "<" in without:
        without = re.sub(r"<[^<>]*>", "", without)
    return without.replace(" ", "")


def top_level_equals(text):
    """The index of the "=" that starts a field's value: outside annotations' parentheses and quotes, or -1."""
    depth, i = 0, 0
    while i < len(text):
        c = text[i]
        if c in "\"'":
            i = skip_quoted(text, i)
            continue
        depth += {"(": 1, ")": -1}.get(c, 0)
        if c == "=" and depth == 0:
            return i
        i += 1
    return -1


# The signature file.

def parse(text, origin, api=None, library=False):
    api = api or Api()
    lines = text.splitlines()
    if not lines or lines[0].strip() != FORMAT:
        raise GeneratorError(f"{origin}:1: not metalava's signature format 2.0")
    package, current = None, None
    for number, line in enumerate(lines[1:], start=2):
        def fail(what):
            raise GeneratorError(f"{origin}:{number}: {what}: {line.strip()}")
        stripped = line.strip()
        if not stripped or stripped.startswith("//"):
            continue
        if package is None:
            match = re.fullmatch(r"package ([\w.]+) \{", stripped)
            if not match:
                fail("expected a package")
            package = match.group(1)
        elif current is None:
            if stripped == "}":
                package = None
            elif stripped.endswith("{"):
                current = parse_type(package, stripped[:-1], fail)
                current.library = library
                if current.qualified in api.types:
                    fail(f"{current.qualified} is declared twice")
                api.types[current.qualified] = current
            else:
                fail("expected a type")
        elif stripped == "}":
            current = None
        else:
            parse_member(current, stripped, fail)
    if package is not None:
        raise GeneratorError(f"{origin}: package {package} is not closed")
    # Linked again over every file read so far, so that a nested type may come in a file after its outer type's.
    for decl in api.types.values():
        decl.nested = []
    for decl in api.types.values():
        if "." in decl.dotted:
            outer = api.types.get(f"{decl.package}.{decl.dotted.rsplit('.', 1)[0]}")
            if outer is None:
                raise GeneratorError(f"{origin}: {decl.qualified} has no outer type")
            outer.nested.append(decl)
    return api


def parse_type(package, header, fail):
    text, kept = strip_annotations(header)
    tokens = split_top(text, " ")
    modifiers = []
    while tokens and tokens[0] in MODIFIERS:
        modifiers.append(tokens.pop(0))
    if not tokens or tokens[0] not in KINDS or len(tokens) < 2:
        fail("cannot read the type")
    kind, name = tokens[0], tokens[1]
    type_parameters = ""
    if "<" in name:
        name, type_parameters = name[:name.index("<")], name[name.index("<"):]
    extends, implements, target = [], [], None
    for token in tokens[2:]:
        if token in ("extends", "implements"):
            target = extends if token == "extends" else implements
        elif target is None:
            fail("cannot read the type")
        else:
            target.append(token)
    # Format 2.0 separates the types of a list with spaces only.
    def listed(types):
        return ", ".join(t.rstrip(",") for t in types)
    return TypeDecl(package, name, kind, modifiers, kept, type_parameters, listed(extends), listed(implements))


def parse_member(decl, line, fail):
    match = re.match(r"(ctor|method|field|enum_constant) (.*);(?:\s*//.*)?$", line)
    if not match:
        fail("cannot read the member")
    what, rest = match.groups()
    if what == "field" or what == "enum_constant":
        value = None
        equals = top_level_equals(rest)
        if equals >= 0:
            rest, value = rest[:equals], rest[equals + 1:].strip()
            if value.startswith('"'):
                value = value[:skip_quoted(value, 0)]
        text, kept = strip_annotations(rest)
        tokens = split_top(text, " ")
        modifiers = []
        while tokens and tokens[0] in MODIFIERS:
            modifiers.append(tokens.pop(0))
        if len(tokens) != 2:
            fail("cannot read the field")
        if what == "enum_constant":
            decl.constants.append(tokens[1])
        else:
            decl.fields.append(Field(modifiers, kept, tokens[0], tokens[1], value))
        return
    # The parameters' parenthesis is the first one outside the annotations.
    text, kept = strip_annotations(line[len(what) + 1:].rstrip())
    text = re.sub(r";(\s*//.*)?$", "", text)
    depth, open_at = 0, -1
    for i, c in enumerate(text):
        if c == "<":
            depth += 1
        elif c == ">":
            depth -= 1
        elif c == "(" and depth == 0:
            open_at = i
            break
    if open_at < 0:
        fail("cannot read the method")
    close_at, depth = open_at, 0
    for i in range(open_at, len(text)):
        depth += {"(": 1, ")": -1}.get(text[i], 0)
        if depth == 0:
            close_at = i
            break
    tokens = split_top(text[:open_at], " ")
    modifiers, type_parameters = [], ""
    while tokens and tokens[0] in MODIFIERS:
        modifiers.append(tokens.pop(0))
    if tokens and tokens[0].startswith("<"):
        type_parameters = tokens.pop(0)
    parameters = split_top(text[open_at + 1:close_at], ",")
    tail = text[close_at + 1:].strip()
    throws, default = "", None
    if " default " in f" {tail} ":
        tail, default = re.split(r"\bdefault\b", tail, maxsplit=1)
        tail, default = tail.strip(), default.strip()
    if tail.startswith("throws "):
        throws = tail[len("throws "):].strip()
    elif tail:
        fail("cannot read the method's end")
    if what == "ctor":
        if len(tokens) != 1:
            fail("cannot read the ctor")
        decl.ctors.append(Method(modifiers, kept, type_parameters, None, tokens[0].rsplit(".", 1)[-1], parameters,
                                 throws, None))
    else:
        if len(tokens) != 2:
            fail("cannot read the method")
        decl.methods.append(Method(modifiers, kept, type_parameters, tokens[0], tokens[1], parameters, throws,
                                   default))


# The hand file.

class HandMember:
    def __init__(self, key, text, added):
        self.key = key
        self.text = text
        self.added = added  # private or @hide: may stand beside the API


def split_members(body):
    """The class body's members, each with the comments before it."""
    members, start, depth, i = [], 0, 0, 0
    while i < len(body):
        c = body[i]
        if body.startswith("//", i):
            i = body.find("\n", i)
            i = len(body) if i < 0 else i
            continue
        if body.startswith("/*", i):
            i = body.index("*/", i) + 2
            continue
        if c in "\"'":
            i = skip_quoted(body, i)
            continue
        if c in "{(":
            depth += 1
        elif c in "})":
            depth -= 1
            if depth == 0 and c == "}":
                # A block member ends here, unless an initializer's ";" follows (a field with an anonymous class).
                rest = body[i + 1:].lstrip(" \t")
                if not rest.startswith(";"):
                    members.append(body[start:i + 1])
                    start = i + 1
        elif c == ";" and depth == 0:
            members.append(body[start:i + 1])
            start = i + 1
        i += 1
    if body[start:].strip() and re.sub(r"//.*|/\*.*?\*/", "", body[start:], flags=re.S).strip():
        raise GeneratorError("text after the last member")
    return [m.strip("\n") for m in members if m.strip()]


def without_comments(text):
    out, i = [], 0
    while i < len(text):
        if text.startswith("//", i):
            end = text.find("\n", i)
            i = len(text) if end < 0 else end
        elif text.startswith("/*", i):
            i = text.index("*/", i) + 2
        elif text[i] in "\"'":
            end = skip_quoted(text, i)
            out.append(text[i:end])
            i = end
        else:
            out.append(text[i])
            i += 1
    return "".join(out)


def read_hand(path, decl):
    with open(path, encoding="utf-8") as hand:
        source = hand.read()
    code = without_comments(source)
    match = re.search(r"\bclass\s+(\w+)\s*\{", code)
    if not match:
        raise GeneratorError(f"{path}: no class body")
    if match.group(1) != decl.name:
        raise GeneratorError(f"{path}: declares class {match.group(1)}, not class {decl.name}")
    imports = re.findall(r"^\s*(import\s+(?:static\s+)?[\w.*]+\s*;)", code[:match.start()], flags=re.M)
    # The body in the source, with its comments: from the class's "{" to the last "}".
    source_open = re.search(r"\bclass\s+" + decl.name + r"\s*\{", source).end()
    body = source[source_open:source.rindex("}")]
    members = []
    for text in split_members(body):
        javadoc = " ".join(re.findall(r"/\*\*.*?\*/", text, flags=re.S))
        code = without_comments(text)
        plain, _ = strip_annotations(code)
        head = re.split(r"[={]", plain, maxsplit=1)[0]
        added = "@hide" in javadoc or re.search(r"\bprivate\b", head) is not None
        nested = re.search(r"\b(class|interface|enum)\s+(\w+)", head)
        if head.strip() in ("", "static"):
            # An initializer block: beside the API, as a private member is.
            key, added = f"init:{len(members)}", True
        elif nested:
            key = f"type:{nested.group(2)}"
        elif "(" in head:
            name = re.search(r"(\w+)\s*\($", head[:head.index("(") + 1]).group(1)
            inside = head[head.index("(") + 1:head.rindex(")")]
            types = []
            for parameter in split_top(inside, ","):
                words = [w for w in split_top(parameter, " ") if w != "final"]
                types.append(erase(" ".join(words[:-1])))
            key = f"{name}({','.join(types)})"
        else:
            name = re.findall(r"(\w+)\s*$", head.rstrip(";").strip())[0]
            key = f"field:{name}"
        members.append(HandMember(key, text, added))
    return imports, members


# The writer.

def default_value(java_type):
    if java_type == "boolean":
        return "false", "false"
    if java_type == "char":
        return "0", "'\\\\0'"
    if java_type in ("byte", "short", "int", "long", "float", "double"):
        return "0", "0"
    return "null", "null"


def superclass(decl, api):
    """The superclass's declaration when it is in the API files."""
    if decl.kind != "class" or not decl.extends:
        return None
    name = log_type(decl.extends)
    return api.types.get(name) or api.types.get(f"{decl.package}.{name}")


def abstract_above(decl, key, api):
    """Whether a superclass in the API files declares the method abstract, so that super cannot call it."""
    parent = superclass(decl, api)
    while parent is not None:
        for method in parent.methods:
            if method.key == key:
                return "abstract" in method.modifiers
        parent = superclass(parent, api)
    return False


# Object's methods by identity, where super cannot be called.
IDENTITY = {"equals(Object)": "this == p0", "hashCode()": "System.identityHashCode(this)",
            "toString()": 'getClass().getName() + "@" + Integer.toHexString(System.identityHashCode(this))'}


def super_call(decl, api):
    """super(...) with defaults, when the superclass is in the API files and has no ctor without parameters."""
    parent = superclass(decl, api)
    if parent is None or not parent.ctors or any(not c.parameters for c in parent.ctors):
        return ""
    # One that throws nothing first, so that the ctor needs no throws clause the API does not list.
    fewest = min(parent.ctors, key=lambda c: (bool(c.throws), len(c.parameters)))
    arguments = []
    for parameter in fewest.parameters:
        java_type = log_type(parameter).replace("...", "[]")
        value = default_value(java_type)[0]
        arguments.append(value if java_type in ("int", "boolean") else f"({java_type}) {value}")
    return f"super({', '.join(arguments)});\n"


def write_type(decl, hand_members, depth, api, stubs=False):
    pad = " " * (4 * depth)
    inner = " " * (4 * (depth + 1))
    out = []
    for annotation in decl.annotations:
        out.append(f"{pad}{annotation}\n")
    header = " ".join(decl.modifiers + [decl.kind, decl.name + decl.type_parameters])
    if decl.extends:
        header += f" extends {decl.extends}"
    if decl.implements:
        header += f" implements {decl.implements}"
    out.append(f"{pad}{header} {{\n")
    hand = {m.key: m for m in hand_members}
    used = set()

    def unknown(*texts):
        # A compile-only stub leaves out a member that names a type in no API file.
        return stubs and any(unknown_names(api, text) for text in texts)

    def take(key):
        if key in hand:
            used.add(key)
            return hand[key].text + "\n"
        return None

    if decl.kind == "enum":
        out.append("".join(f"{inner}{c},\n" for c in decl.constants[:-1]))
        out.append(f"{inner}{decl.constants[-1]};\n" if decl.constants else f"{inner};\n")
    static_init, instance_init = [], []
    for field in decl.fields:
        if unknown(field.type):
            continue
        written = take(f"field:{field.name}")
        if written:
            out.append(written)
            continue
        line = "".join(f"{inner}{a}\n" for a in field.annotations)
        line += f"{inner}{' '.join(field.modifiers + [field.type, field.name])}"
        if field.value is not None:
            line += f" = {field.value}"
        elif "final" in field.modifiers and decl.kind in ("interface", "@interface"):
            line += f" = {default_value(field.type)[0]}"
        elif "final" in field.modifiers:
            (static_init if "static" in field.modifiers else instance_init).append(
                f"{inner}    {field.name} = {default_value(field.type)[0]};\n")
        out.append(line + ";\n")
    if static_init:
        out.append(f"{inner}static {{\n{''.join(static_init)}{inner}}}\n")
    if instance_init:
        out.append(f"{inner}{{\n{''.join(instance_init)}{inner}}}\n")

    hand_ctor = any(k.startswith(decl.name + "(") for k in hand)
    call = super_call(decl, api)
    if decl.kind == "class" and not decl.ctors and not hand_ctor:
        out.append(f"{inner}{decl.name}() {{\n{inner + '    ' + call if call else ''}{inner}}}\n")
    for ctor in decl.ctors:
        if unknown(ctor.throws, *ctor.parameters):
            continue
        written = take(ctor.key)
        if written:
            out.append(written)
            continue
        out.append(method_text(decl, ctor, inner, constructor=True, call=call))
    for method in decl.methods:
        if decl.kind == "enum" and method.key in OBJECT_METHODS | {"values()", "valueOf(String)"}:
            continue
        if unknown(method.returns, method.type_parameters, method.throws, *method.parameters):
            continue
        written = take(method.key)
        if written:
            out.append(written)
            continue
        out.append(method_text(decl, method, inner, identity=abstract_above(decl, method.key, api)))
    for nested in decl.nested:
        if unknown(nested.extends, nested.implements):
            continue
        written = take(f"type:{nested.name}")
        out.append(written if written else write_type(nested, [], depth + 1, api, stubs))
    for member in hand_members:
        if member.key not in used:
            out.append(member.text + "\n")
    out.append(f"{pad}}}\n")
    return "".join(out)


def method_text(decl, method, inner, constructor=False, call="", identity=False):
    out = "".join(f"{inner}{a}\n" for a in method.annotations)
    parameters = ", ".join(f"{t} p{i}" for i, t in enumerate(method.parameters))
    words = list(method.modifiers)
    if method.type_parameters:
        words.append(method.type_parameters)
    if not constructor:
        words.append(method.returns)
    signature = f"{' '.join(words + [method.name])}({parameters})"
    if method.throws:
        signature += f" throws {method.throws}"
    interface = decl.kind in ("interface", "@interface")
    if "abstract" in method.modifiers or (interface and not {"default", "static"} & set(method.modifiers)):
        if method.default is not None:
            signature += f" default {method.default}"
        return f"{out}{inner}{signature};\n"
    body = f"{inner}    "
    if not constructor and method.key in OBJECT_METHODS and "static" not in method.modifiers:
        if identity:
            return f"{out}{inner}{signature} {{\n{body}return {IDENTITY[method.key]};\n{inner}}}\n"
        arguments = ", ".join(f"p{i}" for i in range(len(method.parameters)))
        return f"{out}{inner}{signature} {{\n{body}return super.{method.name}({arguments});\n{inner}}}\n"
    name = decl.qualified if constructor else f"{decl.qualified}.{method.name}"
    logged = f"{name}({','.join(log_type(p) for p in method.parameters)})"
    lines = [f"{body}{call}"] if call else []
    if constructor or method.returns == "void":
        lines.append(f'{body}Unwritten.log("{logged}", null);\n')
    else:
        value, shown = default_value(method.returns)
        lines.append(f'{body}Unwritten.log("{logged}", "{shown}");\n')
        lines.append(f"{body}return {value};\n")
    return f"{out}{inner}{signature} {{\n{''.join(lines)}{inner}}}\n"


def generate(api, classes, hand_folder=None, stubs=False):
    """The Java files for `classes`, as {relative path: text}. As compile-only `stubs`, members that name a type in
    no API file are left out."""
    files = {}
    for name in classes:
        decl = api.types.get(name)
        if decl is None:
            raise GeneratorError(f"{name} is not in the API files")
        if "." in decl.dotted:
            raise GeneratorError(f"{name} is nested: name its outer class")
        if decl.library:
            raise GeneratorError(f"{name} comes from a library's API file, whose classes exist already")
        relative = f"{decl.package.replace('.', '/')}/{decl.name}.java"
        imports, members = [], []
        hand_path = os.path.join(hand_folder, relative) if hand_folder else None
        if hand_path and os.path.exists(hand_path):
            imports, members = read_hand(hand_path, decl)
            known = {f"field:{f.name}" for f in decl.fields} | {c.key for c in decl.ctors} \
                | {m.key for m in decl.methods} | {f"type:{t.name}" for t in decl.nested}
            for member in members:
                if member.key not in known and not member.added:
                    raise GeneratorError(f"{hand_path}: {member.key.removeprefix('field:').removeprefix('type:')} "
                                         f"is not in the API of {name}; mark it @hide if AOSP's classes call it")
        text = [HEADER, f"package {decl.package};\n\n", "import com.android.minato.services.Unwritten;\n"]
        text += [f"{i}\n" for i in sorted(set(imports))]
        text.append("\n")
        text.append(write_type(decl, members, 0, api, stubs))
        files[relative] = "".join(text)
    return files


QUALIFIED = re.compile(r"\b[a-z_]\w*(?:\.[a-z_]\w*)*(?:\.[A-Z]\w*)+")


def top_level(api, name):
    """The top-level declaration that holds `name` (a type, or a nested one), or None."""
    while True:
        decl = api.types.get(name)
        if decl is not None:
            while "." in decl.dotted:
                decl = api.types[f"{decl.package}.{decl.dotted.rsplit('.', 1)[0]}"]
            return decl
        head, _, last = name.rpartition(".")
        if not head or not last[:1].isupper():
            return None
        name = head


def unknown_names(api, text):
    """The qualified names in `text` that no API file declares, but for java.* and javax.*, the boot jars'."""
    return {name for name in QUALIFIED.findall(text or "")
            if top_level(api, name) is None and not name.startswith(("java.", "javax."))}


def signature_texts(decl):
    yield from (decl.extends, decl.implements, decl.type_parameters)
    for method in decl.methods + decl.ctors:
        yield from (method.returns or "", method.type_parameters, method.throws, *method.parameters)
    for field in decl.fields:
        yield field.type
    for nested in decl.nested:
        yield from signature_texts(nested)


def references(api, roots):
    """The top-level types outside the libraries that `roots` reach through their signatures, without the roots:
    the compile-only stubs beside them. A name in no API file is an error in a root, but for java.* and javax.*,
    which the boot jars hold; a stub leaves the member out instead (generate's `stubs`)."""
    seen, queue, found, missing = set(roots), list(roots), set(), set()
    while queue:
        current = queue.pop()
        for text in signature_texts(api.types[current]):
            if current in roots:
                missing |= unknown_names(api, text)
            for name in QUALIFIED.findall(text or ""):
                target = top_level(api, name)
                if target is None:
                    continue
                if target.library or target.qualified in seen:
                    continue
                seen.add(target.qualified)
                found.add(target.qualified)
                queue.append(target.qualified)
    if missing:
        raise GeneratorError("referenced, but in no API file: " + ", ".join(sorted(missing)))
    return sorted(found)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--api", action="append", default=[], help="an API file whose classes may be written")
    parser.add_argument("--all-of", action="append", default=[],
                        help="an API file whose every top-level class is written, as with --class")
    parser.add_argument("--library-api", action="append", default=[],
                        help="a library's API file (libcore's): known, never written")
    parser.add_argument("--class", dest="classes", action="append", default=[])
    parser.add_argument("--hand")
    parser.add_argument("--out", required=True)
    parser.add_argument("--references-out",
                        help="where the types the classes reach go, without hand files: compile-only stubs")
    args = parser.parse_args()
    try:
        api = Api()
        classes = list(args.classes)
        for path in args.library_api + args.api + args.all_of:
            before = set(api.types)
            with open(path, encoding="utf-8") as text:
                parse(text.read(), path, api, library=path in args.library_api)
            if path in args.all_of:
                classes += sorted(n for n in set(api.types) - before if "." not in api.types[n].dotted)
        if not classes:
            raise GeneratorError("no class to write: name one with --class or --all-of")
        outputs = [(args.out, generate(api, classes, args.hand))]
        if args.references_out:
            outputs.append((args.references_out, generate(api, references(api, classes), stubs=True)))
    except GeneratorError as error:
        sys.exit(f"managergen: {error}")
    for folder, files in outputs:
        for relative, text in files.items():
            path = os.path.join(folder, relative)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as out:
                out.write(text)
        print(f"managergen: {len(files)} classes into {folder}")


if __name__ == "__main__":
    main()
