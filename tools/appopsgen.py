#!/usr/bin/env python3
"""Writes AOSP's app op table for our AppOpsManager (ADR-0045 decision 6, the storage and app ops step), as
tools/compatgen.py writes the compat changes: appopsgen.py --source <the tag's AppOpsManager.java> --hand <our
AppOpsManager hand file> --out <folder>, which gets android/app/AppOpsTable.java.

The tag's AppOpsManager holds its ops in sAppOpInfos, indexed by op number (its own sOpStrToOp takes the index): each
with its name, simple name, permission, default mode and switch op. RUNTIME_PERMISSION_OPS names the runtime
permissions' ops. The op numbers themselves come from proto enums that the fetch lacks, so the table's order gives
them, and the hand file's OP_ constants are checked against it. Permissions and modes are written as the Java
expressions the tag uses, so that javac resolves them against framework.jar's android.Manifest and the generated
AppOpsManager's MODE_ constants. Python 3.9."""
import argparse
import os
import re

HEADER = "// Generated by tools/appopsgen.py (ADR-0045 decision 6) from the tag's AppOpsManager.java: its op table.\n"
# One level of nested parentheses, as in setDefaultMode(getSystemAlertWindowDefault()).
CALL = re.compile(r"\.(set\w+)\(((?:[^()]|\([^()]*\))*)\)")
PERMISSION = re.compile(r"(?:android\.)?Manifest\.permission\.(\w+)")
MODE = re.compile(r"(?:AppOpsManager\.)?(MODE_\w+)")


def fail(message):
    raise SystemExit(f"appopsgen: {message}")


def read_table(source):
    """The ops in table order: (code name, name, simple name, permission, mode, switch code name)."""
    names = dict(re.findall(r'public static final String (OPSTR_\w+)\s*=\s*"([^"]*)";', source))
    start = source.find("static final AppOpInfo[] sAppOpInfos = new AppOpInfo[]{")
    if start < 0:
        fail("sAppOpInfos not found")
    end = source.find("\n    };", start)
    entries = source[start:end].split("new AppOpInfo.Builder(")[1:]
    count = re.search(r"public static final int _NUM_OP = (\d+);", source)
    if count is None or int(count.group(1)) != len(entries):
        fail(f"{len(entries)} entries, but _NUM_OP is {count.group(1) if count else 'missing'}")
    ops = []
    for index, entry in enumerate(entries):
        head = re.match(r'\s*(\w+)\s*,\s*("[^"]*"|\w+)\s*,\s*"([^"]*)"\)', entry)
        if head is None:
            fail(f"entry {index} cannot be read: {entry[:80]!r}")
        code, name, simple = head.groups()
        if not name.startswith('"'):
            if name not in names:
                fail(f"entry {index}: {name} is no OPSTR_ constant")
            name = names[name]
        else:
            name = name.strip('"')
        calls = {}
        for setter, argument in CALL.findall(head.string[head.end():]):
            calls[setter] = " ".join(argument.split())
        permission = None
        if "setPermission" in calls:
            match = PERMISSION.fullmatch(calls["setPermission"])
            if match is None:
                fail(f"{code}: permission {calls['setPermission']!r} cannot be read")
            permission = match.group(1)
        mode = "MODE_DEFAULT"
        if "setDefaultMode" in calls:
            argument = calls["setDefaultMode"]
            match = MODE.fullmatch(argument)
            if match is not None:
                mode = match.group(1)
            elif argument == "getSystemAlertWindowDefault()" and code == "OP_SYSTEM_ALERT_WINDOW":
                # MODE_DEFAULT on a phone that is not low on RAM, as Minato's devices are (getSystemAlertWindowDefault).
                mode = "MODE_DEFAULT"
            else:
                fail(f"{code}: default mode {argument!r} cannot be read")
        ops.append((code, name, simple, permission, mode, calls.get("setSwitchCode")))
    return ops


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--source", required=True, help="the tag's core/java/android/app/AppOpsManager.java")
    parser.add_argument("--hand", required=True, help="our AppOpsManager hand file, whose OP_ constants are checked")
    parser.add_argument("--out", required=True, help="the folder that gets android/app/AppOpsTable.java")
    args = parser.parse_args()
    source = open(args.source, encoding="utf-8").read()
    ops = read_table(source)

    numbers = {}
    for index, (code, *_rest) in enumerate(ops):
        if code != "OP_NONE":
            if code in numbers:
                fail(f"{code} stands twice in the table")
            numbers[code] = index
    switches = []
    for index, (code, _name, _simple, _permission, _mode, switch) in enumerate(ops):
        if switch is None:
            switches.append(index)
        elif switch in numbers:
            switches.append(numbers[switch])
        else:
            fail(f"{code}: switch op {switch} is not in the table")
    runtime = re.search(r"RUNTIME_PERMISSION_OPS = \{(.*?)\};", source, re.S)
    if runtime is None:
        fail("RUNTIME_PERMISSION_OPS not found")
    runtime_ops = []
    for code in re.findall(r"\bOP_\w+", re.sub(r"//[^\n]*", "", runtime.group(1))):
        if code not in numbers:
            fail(f"runtime permission op {code} is not in the table")
        runtime_ops.append(numbers[code])
    hand = open(args.hand, encoding="utf-8").read()
    for code, value in re.findall(r"public static final int (OP_\w+) = (-?\d+);", hand):
        if code != "OP_NONE" and numbers.get(code) != int(value):
            fail(f"the hand file's {code} is {value}, the table's {numbers.get(code)}")
    count = re.search(r"public static final int _NUM_OP = (\d+);", hand)
    if count is not None and int(count.group(1)) != len(ops):
        fail(f"the hand file's _NUM_OP is {count.group(1)}, the table's {len(ops)}")

    folder = os.path.join(args.out, "android", "app")
    os.makedirs(folder, exist_ok=True)
    with open(os.path.join(folder, "AppOpsTable.java"), "w", encoding="utf-8") as out:
        out.write(HEADER)
        out.write("package android.app;\n\n")
        out.write("/** @hide AOSP's app ops by number, as the tag's sAppOpInfos holds them. */\n")
        out.write("final class AppOpsTable {\n")
        out.write("    /** Each op's name, by number. */\n    static final String[] NAMES = {\n")
        out.writelines(f'        "{name}",\n' for _code, name, *_rest in ops)
        out.write("    };\n    /** Each op's simple name, which AOSP's SecurityException names. */\n")
        out.write("    static final String[] SIMPLE_NAMES = {\n")
        out.writelines(f'        "{simple}",\n' for _code, _name, simple, *_rest in ops)
        out.write("    };\n    /** Each op's permission, or null. */\n    static final String[] PERMISSIONS = {\n")
        out.writelines(f"        {'android.Manifest.permission.' + permission if permission else 'null'},\n"
                       for _code, _name, _simple, permission, *_rest in ops)
        out.write("    };\n    /** Each op's default mode. */\n    static final int[] DEFAULT_MODES = {\n")
        out.writelines(f"        AppOpsManager.{mode},\n" for *_rest, mode, _switch in ops)
        out.write("    };\n    /** The op whose mode each op shares, as AppOpsService answers it; itself by default. "
                  "*/\n")
        out.write("    static final int[] SWITCH_OPS = {\n")
        out.writelines(f"        {switch},\n" for switch in switches)
        out.write("    };\n    /** The runtime permissions' ops, as the tag's RUNTIME_PERMISSION_OPS. */\n")
        out.write("    static final int[] RUNTIME_PERMISSION_OPS = {\n")
        out.writelines(f"        {op},\n" for op in runtime_ops)
        out.write("    };\n\n    private AppOpsTable() {\n    }\n}\n")
    print(f"appopsgen: {len(ops)} ops, {len(runtime_ops)} of runtime permissions")


if __name__ == "__main__":
    main()
