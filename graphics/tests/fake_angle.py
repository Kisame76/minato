#!/usr/bin/env python3
"""Test 5 of ADR-0029: fake-angle, host code in ANGLE's place for graphics.gles_thunk. Every GLES name of
tools/frontgen's list (gles_names.inc) is a branch to one recording function, which stores x0-x7, v0-v7 and
the 128 bytes from the stack pointer as they arrive behind the runtime's entry, counts the call and returns
the record's address in x0 and the record's results in x1 and v0-v3. The record's layout is
gles_thunk_test.c's struct fake_record.

  fake_angle.py --names build/graphics/gen/gles_names.inc --out fake_angle.S"""
import argparse
import re
import sys

MAGIC = 0x6d696e61746f4641  # "minatoFA"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--names", required=True)
    parser.add_argument("--out", required=True)
    options = parser.parse_args()
    with open(options.names) as file:
        names = re.findall(r'^MINATO_NAME\(\w+, "(\w+)", ', file.read(), re.M)
    if not names:
        raise SystemExit(f"fake_angle: no names in {options.names}")
    lines = ["// Generated by graphics/tests/fake_angle.py from gles_names.inc; do not edit.", "", "    .text",
             "    .p2align 2", "record:", "    adrp x16, _fake_angle_record@PAGE",
             "    add x16, x16, _fake_angle_record@PAGEOFF"]
    lines += [f"    stp x{2 * n}, x{2 * n + 1}, [x16, #{16 * n}]" for n in range(4)]
    lines += [f"    stp q{2 * n}, q{2 * n + 1}, [x16, #{64 + 32 * n}]" for n in range(4)]
    lines += ["    mov x9, sp"]
    for n in range(8):
        lines += [f"    ldp x10, x11, [x9, #{16 * n}]", f"    stp x10, x11, [x16, #{192 + 16 * n}]"]
    lines += ["    ldr x10, [x16, #400]", "    add x10, x10, #1", "    str x10, [x16, #400]",
              "    ldr x1, [x16, #320]", "    ldp q0, q1, [x16, #336]", "    ldp q2, q3, [x16, #368]",
              "    mov x0, x16", "    ret", ""]
    for name in sorted(set(names)):
        lines += [f"    .globl _{name}", "    .p2align 2", f"_{name}:", "    b record"]
    lines += ["", "    .data", "    .p2align 4", "    .globl _fake_angle_record", "_fake_angle_record:",
              "    .space 408", f"    .quad {MAGIC:#x}", ""]
    with open(options.out, "w") as file:
        file.write("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
