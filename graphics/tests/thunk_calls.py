#!/usr/bin/env python3
"""Test 2 of ADR-0030, its call list: for every stub that tools/frontgen writes, the arguments of its
function as the C headers declare them, and where each lies in AAPCS64 and in Apple's ABI, as
thunk_calls.c for thunk_test.c.

The types come from the NDK's C headers (ndk_headers.py) or, for the names the NDK lacks, from the host
library's own headers (ANGLE's include/, MoltenVK's include/), never from the Khronos XML that the stubs
are made of. Only the names, their slots and which of them are written by hand come from the generator.

  thunk_calls.py --gen build/graphics/gen --out thunk_calls.c --ndk DIR --angle DIR --moltenvk DIR"""
import argparse
import json
import os
import sys

import ndk_headers

LIBS = ("vulkan", "gles", "egl")
STACK_BYTES = 128   # the stack area thunk_call passes (thunk_test.S)
KINDS = {"int": "THUNK_INT", "float": "THUNK_FLOAT", "pointer": "THUNK_POINTER", "callback": "THUNK_POINTER"}


def arguments(prototype):
    """The thunk_arg initializers of one prototype."""
    result = []
    for param, place in zip(prototype.params, ndk_headers.places(prototype.params)):
        if param.kind not in KINDS:
            raise SystemExit(f"thunk_calls: {prototype.name} passes {param.kind} {param.text!r}, which no stub "
                             f"may pass")
        kind = "THUNK_ALLOCATOR" if "VkAllocationCallbacks" in param.text else KINDS[param.kind]
        if place[0] == "stack":
            if place[1] + 8 > STACK_BYTES or place[2] + param.size > STACK_BYTES:
                raise SystemExit(f"thunk_calls: {prototype.name} needs more than {STACK_BYTES} stack bytes")
            where, index, aapcs, apple = "THUNK_STACK", 0, place[1], place[2]
        else:
            where, index, aapcs, apple = ("THUNK_X" if place[0] == "x" else "THUNK_V"), place[1], 0, 0
        result.append(f"{{{kind}, {param.size}, {int(bool(param.signed))}, {where}, {index}, {aapcs}, {apple}}}")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--gen", required=True, help="tools/frontgen's output folder")
    parser.add_argument("--out", required=True)
    parser.add_argument("--ndk", required=True)
    parser.add_argument("--angle", required=True, help="ANGLE's checkout, for its include/")
    parser.add_argument("--moltenvk", required=True, help="build/moltenvk, for MoltenVK's include/")
    options = parser.parse_args()
    host_include = {"vulkan": os.path.join(options.moltenvk, "include"),
                    "gles": os.path.join(options.angle, "include"), "egl": os.path.join(options.angle, "include")}

    declarations, args, calls = [], [], []
    for number, lib in enumerate(LIBS):
        with open(os.path.join(options.gen, f"{lib}_report.json")) as file:
            table = json.load(file)["table"]
        ndk = ndk_headers.Headers(options.ndk, lib).prototypes
        host = ndk_headers.Headers(options.ndk, lib, include=host_include[lib]).prototypes
        for entry in table:
            name = entry["name"]
            prototype, source = (ndk[name], "THUNK_NDK") if name in ndk else (host.get(name), "THUNK_HOST")
            if prototype is None:
                raise SystemExit(f"thunk_calls: {lib}: {name} is in no C header")
            stub = f"minato_host_{name}" if entry["kind"] == "by hand" else name
            declarations.append(f"void {stub}(void);")
            first = len(args)
            args += arguments(prototype)
            calls.append(f"    {{\"{name}\", {stub}, {number}, {source}, MINATO_{lib.upper()}_SLOT_{name}, "
                         f"{first}, {len(args) - first}}},")

    text = [f"/* Generated by graphics/tests/thunk_calls.py from the C headers of the NDK, ANGLE and MoltenVK; "
            f"do not edit. */",
            '#include "thunk_test.h"', '#include "egl_table.h"', '#include "gles_table.h"',
            '#include "vulkan_table.h"', ""]
    text += declarations + ["", "const struct thunk_arg thunk_args[] = {"]
    text += [f"    {arg}," for arg in args] + ["};", "", "const struct thunk_call thunk_calls[] = {"]
    text += calls + ["};", "const unsigned thunk_call_count = sizeof thunk_calls / sizeof thunk_calls[0];", ""]
    with open(options.out, "w") as file:
        file.write("\n".join(text))
    return 0


if __name__ == "__main__":
    sys.exit(main())
